export const INITIAL_DISASTER_EVENTS: CalamityEvent[] = BASE_DISASTER_EVENTS.map((ev, idx) => {
  // Stagger events between 18 minutes ago and 16 hours ago so they represent recent active incidents
  const minutesAgo = 18 + (idx * 32) % (16 * 60);
  const eventTime = new Date(Date.now() - minutesAgo * 60 * 1000).toISOString();
  const rawSourceUrl = ev.type === 'earthquake' 
    ? `https://earthquake.usgs.gov/earthquakes/map/?extent=${(ev.coordinates.lat - 2).toFixed(2)},${(ev.coordinates.lng - 2).toFixed(2)},${(ev.coordinates.lat + 2).toFixed(2)},${(ev.coordinates.lng + 2).toFixed(2)}`
    : ev.type === 'volcano'
    ? 'https://volcano.si.edu/reports_weekly.cfm'
    : ev.type === 'wildfire'
    ? 'https://firms.modaps.eosdis.nasa.gov/'
    : 'https://www.gdacs.org/Alerts/default.aspx';

  return {
    ...ev,
    occurredAt: eventTime,
    updatedAt: eventTime,
    isLiveFeed: true,
    rawFeedUrl: rawSourceUrl,
    liveFeedSource: ev.source.split(' ')[0] || 'GLOBAL_NETWORK',
    liveIngestionTime: minutesAgo < 60 ? `${minutesAgo}m ago` : `${Math.floor(minutesAgo / 60)}h ${minutesAgo % 60}m ago`,
  };
});
